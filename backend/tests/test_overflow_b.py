"""失败测乙：水位对账把溢出丢点误标已入栏（假绿）则红。

假绿分属装载（报告计数）与目录（只读裁决接口）两处，两侧都不许把溢点算进在栏。
旁路账册钉指纹，且拒回刷：超容点重发只能幂等驳回，永不回流现行缓冲。
"""
from app.services import 装载, 目录, 贯验


def _报文(n: int, 批次: str = "ov-b") -> dict:
    return {
        "报文编号": f"{批次}-{n}",
        "站点键": "站-北岭",
        "指标键": "PM25",
        "读数": 30.0 + n,
        "观测时": f"2026-11-25T09:{n:02d}:00Z",
    }


def test_溢出点不得误标已入栏且账实可对账():
    目录.改栏规({"入栏容限": "2"})
    报告 = 装载.装一批({"批次编号": "ov-b", "报文": [_报文(i) for i in range(4)]})

    # 装载侧假绿防线：入流去向只有入栏/坏点/溢出三条，计数闭合
    assert 报告["入流"] == 报告["入栏"] + 报告["坏点"] + 报告["溢出"]
    assert 报告["入栏"] == 2
    assert 报告["溢出"] == 2

    from app.services import 溢出
    裁决 = 溢出.裁决快照()
    # 目录侧假绿防线：只读裁决接口的对账必须显式对齐，而不是把溢点算绿
    assert 裁决["对账"]["是否对齐"] is True
    assert 裁决["水位"]["在栏"] == 2
    assert 裁决["水位"]["溢出"] == 2

    归档 = 裁决["归档"]
    归档编号 = {r["报文编号"] for r in 归档}
    报文命运 = {r["报文编号"]: r["命运"] for r in 目录.报文列表()}
    for 编号 in 归档编号:
        # 关键红处：溢点命运必须是已溢出，绝不能是已入栏
        assert 报文命运[编号] == "已溢出"
        assert 报文命运[编号] != "已入栏"

    # 账册钉死指纹：指纹可复算、归档只读留痕
    for r in 归档:
        assert r["指纹"] == 溢出.指纹(r)
        assert len(r["指纹"]) >= 12
        assert r["原因"] == "入栏容限溢出"

    # 贯验口径同步：入流 = 在栏 + 已汇总 + 坏点 + 溢出，假绿无处藏
    snap = 贯验.只读快照()
    assert snap["溢出"] == 2
    assert snap["是否对齐"] is True


def test_溢出点拒回刷重发只走幂等驳回():
    目录.改栏规({"入栏容限": "1"})
    装载.装一批({"批次编号": "ov-r", "报文": [_报文(i, "ov-r") for i in range(3)]})
    assert len([r for r in 目录.缓冲列表() if r["命运"] == "在栏"]) == 1

    # 重发被切流的溢点：不得回刷进现行，只能幂等驳回
    重发 = 装载.装一批({"批次编号": "ov-r-2", "报文": [_报文(2, "ov-r")]})
    assert 重发["驳回"] == 1
    assert 重发["入栏"] == 0
    assert len([r for r in 目录.缓冲列表() if r["命运"] == "在栏"]) == 1
