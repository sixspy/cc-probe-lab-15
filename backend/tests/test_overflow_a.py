"""失败测甲：超容后正式在栏仍突破容限则红。

串：栏规（钉容限）→ 装载 → 入栏缓冲（现行集）→ 溢出归档（旁路）。
超容点装载后，现行缓冲是否仍增行必须可区分：现行集与旁路指纹集不相交。
"""
from app.services import 装载, 目录, 夹具


def _报文(n: int) -> dict:
    return {
        "报文编号": f"ov-a-{n}",
        "站点键": "站-河东",
        "指标键": "PM25",
        "读数": 20.0 + n,
        "观测时": f"2026-11-25T08:{n:02d}:00Z",
    }


def test_超容后现行在栏不得突破容限():
    目录.改栏规({"入栏容限": "3"})
    报告 = 装载.装一批({"批次编号": "ov-a", "报文": [_报文(i) for i in range(5)]})

    在栏 = [r for r in 目录.缓冲列表() if r["命运"] == "在栏"]
    # 现行缓冲只读容限内集：不得突破容限
    assert len(在栏) <= 3
    assert 报告["入栏"] == 3
    # 溢出点必须有明确命运，不许静默丢
    assert 报告["溢出"] == 2

    from app.services import 溢出
    归档 = 溢出.归档列表()
    assert len(归档) == 2

    # 双轨读引用不同：超容点装载后现行是否增行可区分——两轨不相交
    现行编号 = {r["报文编号"] for r in 在栏}
    旁路编号 = {r["报文编号"] for r in 归档}
    assert 现行编号.isdisjoint(旁路编号)
    assert {"ov-a-3", "ov-a-4"} == 旁路编号
    # 现行缓冲保持容限内的前三行
    assert 现行编号 == {"ov-a-0", "ov-a-1", "ov-a-2"}


def test_容限未设时基线happy_path不破():
    # 不设入栏容限：五件全进现行，基线行为不变
    报告 = 装载.装一批({"批次编号": "ov-a-base", "报文": [_报文(i) for i in range(10, 15)]})
    assert 报告["入栏"] == 5
    assert 报告["溢出"] == 0


def test_清空容限即停用策略回退基线():
    目录.改栏规({"入栏容限": "2"})
    装载.装一批({"批次编号": "ov-a-off-1", "报文": [_报文(i) for i in range(20, 24)]})
    from app.services import 溢出
    assert 溢出.裁决快照()["启用"] is True

    # 显式清空：栏规键删除，后续装载不再切流，全部入现行
    规 = 目录.改栏规({"入栏容限": ""})
    assert "入栏容限" not in 规
    报告 = 装载.装一批({"批次编号": "ov-a-off-2", "报文": [_报文(i) for i in range(30, 34)]})
    assert 报告["入栏"] == 4
    assert 报告["溢出"] == 0
    assert 溢出.裁决快照()["启用"] is False


def test_溢出夹具串装载入栏缓冲归档():
    # 夹具：容限内成片（3），超容切流（2），现行不破容、双写归档有溢出
    预检 = 夹具.预检("入栏溢出样例")
    assert 预检["是否可装"] and 预检["报文数"] == 5
    目录.改栏规({"入栏容限": "3"})
    报告 = 装载.装一批(夹具.读取("入栏溢出样例"))
    assert 报告["入栏"] == 3 and 报告["溢出"] == 2
    from app.services import 溢出
    归档 = 溢出.归档列表()
    assert {r["报文编号"] for r in 归档} == {"P-ov-4", "P-ov-5"}
    assert 溢出.裁决快照()["对账"]["是否对齐"] is True
